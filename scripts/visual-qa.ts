/**
 * Visual QA: screenshots every route at 1440, 1024 and 390 and writes side-by-side images next to
 * the rendered mockups (run `pnpm render:mockups` first). Output: qa/screens, qa/compare, qa/report.md.
 * Usage: start the app (pnpm start), then `pnpm qa [--base http://127.0.0.1:3000]`.
 */
import fs from "node:fs";
import path from "node:path";
import { chromium } from "@playwright/test";
import { compareScreenshots } from "../lib/qa/compare";

const args = process.argv.slice(2);
const base = args.includes("--base") ? args[args.indexOf("--base") + 1] : "http://127.0.0.1:3000";
const OUT = path.resolve("qa/screens");
const CMP = path.resolve("qa/compare");
fs.mkdirSync(OUT, { recursive: true });
fs.mkdirSync(CMP, { recursive: true });

const ROUTES: Array<{ route: string; mock?: string; phoneMock?: string; beats?: number }> = [
  { route: "/", mock: "Main", phoneMock: "M-Landing" },
  { route: "/floor", mock: "World", phoneMock: "M-World" },
  { route: "/create", mock: "Create" },
  { route: "/pitch/latest", mock: "PitchRoom-beat4", phoneMock: "M-Pitch", beats: 4 },
  { route: "/offers/FIRST", mock: "TermSheet" },
  { route: "/company/mine", mock: "Company", phoneMock: "M-Company" },
  { route: "/fund/mine", mock: "Fund" },
  { route: "/wire", mock: "Gossip" },
  { route: "/demo-day", mock: "DemoDay" },
  { route: "/cards", mock: "Cards" },
  { route: "/dev/components" },
  { route: "/admin" },
];

const browser = await chromium.launch();
const rows: string[] = ["| Route | Width | Mockup | Diff vs mockup (common area) |", "|---|---|---|---|"];
for (const width of [1440, 1024, 390]) {
  const ctx = await browser.newContext({ viewport: { width, height: width < 640 ? 844 : 1000 }, reducedMotion: "reduce" });
  const page = await ctx.newPage();
  for (const r of ROUTES) {
    let route = r.route;
    if (route === "/offers/FIRST") {
      await page.goto(`${base}/floor`);
      route = (await page.locator('a[href^="/offers/"]').first().getAttribute("href").catch(() => null)) ?? "/floor";
    }
    await page.goto(base + route, { waitUntil: "load" });
    await page.evaluate(() => document.fonts.ready);
    for (let i = 0; i < (r.beats ?? 0); i++) await page.getByRole("button", { name: "Next reaction" }).click();
    await page.waitForTimeout(250);
    const name = `${r.route === "/" ? "home" : r.route.slice(1).replace(/[/?=&]/g, "_")}@${width}`;
    const file = path.join(OUT, `${name}.png`);
    await page.screenshot({ path: file, fullPage: true });
    const mock = width === 390 ? r.phoneMock : width === 1440 ? r.mock : undefined;
    const ref = mock ? path.resolve("design/rendered", `${mock}.png`) : null;
    if (ref && fs.existsSync(ref)) {
      const res = compareScreenshots(ref, file, CMP);
      rows.push(`| ${r.route} | ${width} | ${mock} | ${(res.diffRatio * 100).toFixed(1)}% · ${path.relative(process.cwd(), res.sideBySidePath!)} |`);
    } else rows.push(`| ${r.route} | ${width} | — | screenshot only |`);
    console.log(`shot ${name}`);
  }
  await ctx.close();
}
await browser.close();
fs.writeFileSync(
  "qa/report.md",
  `# Visual QA\n\nGenerated by \`pnpm qa\`. Pixel diffs compare live seeded data with static mockup copy, so they measure layout drift, not equality. Review the side-by-side images.\n\n${rows.join("\n")}\n`,
);
console.log("wrote qa/report.md");
